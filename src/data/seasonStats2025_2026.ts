/**
 * Fuzzy search helper to match player names from Excel with 2025/2026 database stats
 */
export function find20252026Stats(playerName: string, team?: string): HistoricalPlayerSeasonStats | null {
  if (!playerName) return null;
  const cleanName = playerName.toLowerCase().trim().replace(/[^a-z0-9\s]/g, '');

  // Exact key check
  if (SEASON_STATS_2025_2026[cleanName]) {
    return SEASON_STATS_2025_2026[cleanName];
  }

  // Check aliases and partial names
  for (const [key, stat] of Object.entries(SEASON_STATS_2025_2026)) {
    if (key === cleanName || cleanName.includes(key) || key.includes(cleanName)) {
      return stat;
    }
    if (stat.aliases && stat.aliases.some(a => cleanName.includes(a.toLowerCase()) || a.toLowerCase().includes(cleanName))) {
      return stat;
    }
    // Match by surname
    const parts = cleanName.split(' ');
    const surname = parts[parts.length - 1];
    if (surname.length >= 4 && key.includes(surname)) {
      // If team also matches or is provided
      if (!team || !stat.squadra2526 || team.toLowerCase().includes(stat.squadra2526.toLowerCase()) || stat.squadra2526.toLowerCase().includes(team.toLowerCase())) {
        return stat;
      }
    }
  }

  return null;
}
